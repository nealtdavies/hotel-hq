'use strict';
/* Builds js/names-data.js from the names PDF (1,000 gender-labelled first names and 1,000 surnames).
   Needs the pdftotext tool. Usage: node tools/make-names.js [path/to/names.pdf] */
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const root = path.join(__dirname, '..');
const pdf = process.argv[2] || path.join(root, 'data', 'names-source.pdf');
const text = execFileSync('pdftotext', ['-layout', pdf, '-'], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });
const lines = text.split('\n');
const split = lines.findIndex(l => l.trim() === 'SURNAMES');
if (split < 0) throw new Error('Could not find the SURNAMES section');
const cols = l => l.trim().split(/\s{2,}/).filter(Boolean);
const GCODE = { Male: 'm', Female: 'f', Unisex: 'u' };
const first = new Map(), sur = new Map();
for (const l of lines.slice(0, split)) { const t = cols(l); for (let i = 0; i + 2 < t.length + 0; i += 3) if (/^\d{4}$/.test(t[i]) && GCODE[t[i + 2]]) first.set(Number(t[i]), [t[i + 1], GCODE[t[i + 2]]]); }
for (const l of lines.slice(split)) { const t = cols(l); for (let i = 0; i + 1 < t.length; i += 2) if (/^\d{4}$/.test(t[i]) && !/^\d{4}$/.test(t[i + 1])) sur.set(Number(t[i]), t[i + 1]); }
const firstNames = [...first.entries()].sort((a, b) => a[0] - b[0]).map(e => e[1]);
const allSur = [...sur.entries()].sort((a, b) => a[0] - b[0]).map(e => e[1]);
if (firstNames.length !== 1000) throw new Error(`Expected 1000 first names, found ${firstNames.length}`);
if (allSur.length !== 1000) throw new Error(`Expected 1000 surnames, found ${allSur.length}`);
// The source list contains fragments of double-barrelled surnames ("de", "Le", "van", "Da") as entries of their own. They are not surnames.
const fragment = s => s.length <= 2 || s === s.toLowerCase();
const surnames = allSur.filter(s => !fragment(s));
const dropped = allSur.filter(fragment);
const out = `'use strict';

/* GENERATED by tools/make-names.js from data/names-source.pdf. Do not edit by hand.
   FIRST_NAMES: [name, gender] where gender is m (male), f (female) or u (unisex).
   SURNAMES: ${surnames.length} surnames. Left out because they are fragments, not surnames: ${dropped.join(', ')}. */
const FIRST_NAMES = ${JSON.stringify(firstNames)};
const SURNAMES = ${JSON.stringify(surnames)};
`;
fs.writeFileSync(path.join(root, 'js', 'names-data.js'), out);
const count = g => firstNames.filter(n => n[1] === g).length;
console.log(`first names: ${firstNames.length} (${count('f')} female, ${count('m')} male, ${count('u')} unisex); surnames kept: ${surnames.length}; left out: ${dropped.length} (${dropped.join(', ')})`);
